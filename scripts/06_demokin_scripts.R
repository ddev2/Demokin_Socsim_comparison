MAX_AGE   <- 100     # last age given to DemoKin
# >>> results folder as in config.R (environment variable KIN_RESULTS_DIR), start
RESULTS_DIR <- Sys.getenv("KIN_RESULTS_DIR", file.path(REPO_DIR, "results"))
# <<< end
EGO_AGE   <- 65      # age of ego at which kin are counted
OUT_DIR   <- file.path(REPO_DIR, "demokin")
SCENARIOS <- utils::read.csv(file.path(REPO_DIR, "scenarios", "scenarios.csv"),
                             stringsAsFactors = FALSE)
dir.create(OUT_DIR, showWarnings = FALSE)


# ==== 1. Rates of a scenario ====

ratesFile <- function(s) {
  f <- file.path(RESULTS_DIR, "empirical_rates", paste0(s, ".csv"))
  if (!file.exists(f)) f <- file.path(REPO_DIR, "data", "empirical_rates", paste0(s, ".csv"))
  f
}

# Same computation as demokinInputs() in R/demokin_lib.R
ratesForDemoKin <- function(r, maxAge = MAX_AGE) {
  r  <- r[r$age <= maxAge, ]
  mx <- ifelse(r$expo > 0, r$deaths / r$expo, 1)
  px <- exp(-mx)
  px[length(px)] <- 0
  fx <- ifelse(r$expo > 0, r$births / r$expo, 0)
  list(age = r$age, px = px, fx = fx, pf = sum(r$bdau) / sum(r$births))
}


# ==== 2. Write one script per scenario ====

vec <- function(x, per_line = 6) {
  v <- trimws(formatC(x, digits = 10, format = "g"))
  lines <- split(v, ceiling(seq_along(v) / per_line))
  paste0("c(", paste(vapply(lines, paste, character(1), collapse = ", "),
                     collapse = ",\n  "), ")")
}

writeScenarioScript <- function(row) {
  s   <- row$scenario
  inp <- ratesForDemoKin(utils::read.csv(ratesFile(s)))
  txt <- c(
    "# >>> generated by scripts/06_demokin_scripts.R, start",
    paste0("# DemoKin with the female rates of the Socsim run ", s, "."),
    paste0("# Population: ", row$population, "; mortality: ", row$mortality,
           "; minimum birth interval (bint): ", row$bint, " months; heterogeneity (hetfert): ",
           row$hetfert, "."),
    "# Rates estimated from the last 100 years of the run (see scripts/06_demokin_scripts.R):",
    "#   px: survival probabilities exp(-m(x)), ages 0 to 100, closed at age 100",
    "#   fx: births of both sexes per woman-year, ages 0 to 100",
    "#   pf: proportion of female births in the same years",
    "# Only the DemoKin package is needed (version 1.0.3 in the paper).",
    "",
    "library(DemoKin)",
    "",
    "",
    "# ==== 1. Rates ====",
    "",
    paste0("scenario <- \"", s, "\""),
    paste0("px <- ", vec(inp$px)),
    "",
    paste0("fx <- ", vec(inp$fx)),
    "",
    paste0("pf <- ", formatC(inp$pf, digits = 10, format = "g")),
    "",
    "",
    "# ==== 2. DemoKin, one-sex time-invariant model ====",
    "",
    "k <- DemoKin::kin(p = px, f = fx, time_invariant = TRUE, birth_female = pf,",
    "                  output_kin = c(\"d\", \"os\", \"ys\", \"oa\", \"ya\", \"coa\", \"cya\", \"nos\", \"nys\"))",
    "",
    "",
    paste0("# ==== 3. Kin ever born at age ", EGO_AGE, " of ego ===="),
    "",
    "# Kin ever born at exact age x: count_living(x) + count_cum_dead(x - 1), the kin alive",
    "# at the birth of ego or born after it",
    "s <- k$kin_summary",
    "s <- s[order(s$kin, s$age_focal), ]",
    "s$count_everborn <- s$count_living +",
    "  stats::ave(s$count_cum_dead, s$kin, FUN = function(z) c(0, z[-length(z)]))",
    "everborn <- function(kins) sum(s$count_everborn[s$kin %in% kins & s$age_focal == age])",
    paste0("age <- ", EGO_AGE),
    "res <- data.frame(scenario = scenario, TFR = sum(fx), e0 = sum(cumprod(c(1, px))[1:length(px)]) - 0.5,",
    "                  sisters = everborn(c(\"os\", \"ys\")), aunts = everborn(c(\"oa\", \"ya\")),",
    "                  cousins = everborn(c(\"coa\", \"cya\")), nieces = everborn(c(\"nos\", \"nys\")),",
    "                  daughters = everborn(\"d\"))",
    "print(res, digits = 3)",
    "invisible(res)",
    "# <<< end"
  )
  writeLines(txt, file.path(OUT_DIR, paste0(s, ".R")))
  s
}

done <- vapply(split(SCENARIOS, seq_len(nrow(SCENARIOS))), writeScenarioScript, character(1))
message(length(done), " scripts written to ", OUT_DIR)


