# >>> new script, one self-contained DemoKin script per scenario, start
# Step 6. One self-contained DemoKin script per Socsim scenario.
#
# For each of the 32 scenarios, this script reads the female rates estimated from the
# Socsim run (data/empirical_rates/<scenario>.csv, or results/empirical_rates/ if step 2
# has been run) and writes demokin/<scenario>.R, a short R script that contains the
# rates given to DemoKin and runs it. Each of these scripts needs only the DemoKin
# package: it can be read and run on its own, without the rest of the repository.
#
# How the rates are obtained from a Socsim run (empiricalRates() in R/kin_count_lib.R):
#   - period: the last 100 years of the run;
#   - exposure E(x): years lived by women at age x (single years) during the period,
#     computed from their dates of birth and death in months;
#   - deaths D(x): deaths of women during the period, by age at death in completed years;
#   - births B(x) and Bf(x): births of both sexes and of daughters during the period, by
#     the age of the mother at the birth in completed years.
# From these counts (demokinInputs() in R/demokin_lib.R):
#   - death rate m(x) = D(x) / E(x) and survival probability p(x) = exp(-m(x)), with
#     p(100) = 0 to close the life table;
#   - fertility rate f(x) = B(x) / E(x), births of both sexes per woman-year;
#   - proportion of female births pf = sum(Bf) / sum(B), which DemoKin applies to f(x).
# Kin ever born at exact age x of ego are count_living(x) + count_cum_dead(x - 1),
# because DemoKin records at age x the deaths of the following year: the kin alive at
# the birth of ego or born after it (section 4.3 of the paper).
#
# Output:
#   demokin/<scenario>.R            one script per scenario
#   demokin/run_all.R               runs the 32 scripts and collects their results
# Each script, when run, prints the kin ever born at age 65 and returns them.


